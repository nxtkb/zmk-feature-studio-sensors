#!/usr/bin/env python3
"""Export only this module's integration changes from pinned local worktrees."""
import argparse
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ZMK_BASE = '4de313367288aad5aeaa1243890e40dc813f7008'
MESSAGES_BASE = '6cb4c283e76209d59c45fbcb218800cd19e9339d'
CORE_FILES = [
    'app/CMakeLists.txt',
    'app/include/drivers/behavior.h', 'app/include/zmk/keymap.h',
    'app/dts/behaviors/sensor_rotate_key_press.dtsi',
    'app/dts/bindings/behaviors/zmk,behavior-sensor-rotate.yaml',
    'app/dts/bindings/behaviors/zmk,behavior-sensor-rotate-var.yaml',
    'app/src/behaviors/behavior_sensor_rotate.c',
    'app/src/behaviors/behavior_sensor_rotate_var.c',
    'app/src/behaviors/behavior_sensor_rotate_common.c',
    'app/src/behaviors/behavior_sensor_rotate_common.h',
    'app/src/keymap.c', 'app/src/physical_layouts.c',
]
TRANSPORT_FILES = ['app/src/studio/rpc.c', 'app/src/studio/gatt_rpc_transport.c']

def git(path, *args, allowed=(0,)):
    result = subprocess.run(['git', '-C', str(path), *args], capture_output=True)
    if result.returncode not in allowed:
        raise RuntimeError(result.stderr.decode())
    return result.stdout

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--zmk', type=Path, required=True)
    parser.add_argument('--messages', type=Path, required=True)
    args = parser.parse_args()
    for checkout, revision in [(args.zmk, ZMK_BASE), (args.messages, MESSAGES_BASE)]:
        if git(checkout, 'rev-parse', 'HEAD').decode().strip() != revision:
            raise SystemExit(f'{checkout} must be at pinned revision {revision}')
    core = git(args.zmk, 'diff', '--binary', 'HEAD', '--', *CORE_FILES)
    transport = git(args.zmk, 'diff', '--binary', 'HEAD', '--', *TRANSPORT_FILES)
    messages = git(args.messages, 'diff', '--binary', 'HEAD', '--', 'proto/zmk/keymap.proto')
    for name in ['sensors.proto', 'sensors.options']:
        target = args.messages / 'proto/zmk' / name
        target.write_bytes((ROOT / 'protocol/local' / name).read_bytes())
        messages += git(args.messages, 'diff', '--no-index', '--binary', '--',
                        '/dev/null', 'proto/zmk/' + name, allowed=(1,))
    entries = [
        ('zmk', 'zmk/studio-sensors-local.patch', core),
        ('zmk', 'zmk/studio-rpc-tx-backpressure.patch', transport),
        ('zmk-studio-messages', 'zmk-studio-messages/studio-sensors-local.patch', messages),
    ]
    manifest = ['# Generated by scripts/export_patches.py; pinned NXTKB extension 0.1.', 'patches:']
    for module, name, data in entries:
        if not data:
            raise SystemExit(f'No integration changes found for {module}')
        target = ROOT / 'zephyr/patches' / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        digest = hashlib.sha256(data).hexdigest()
        manifest += [f'  - path: {name}', f'    sha256sum: {digest}',
                     f'    module: {module}', '    author: NXTKB',
                     '    email: sky_io@outlook.com', '    date: 2026-11-17',
                     '    upstreamable: false', '    apply-command: git apply',
                     '    comments: |',
                     '      NXTKB extension 0.1; field 101 is private, not allocated upstream.',
                     '      Apply all manifest entries to official ZMK 4de31336/messages 6cb4c28.',
                     '      Enable explicitly with the studio-sensors-local snippet.']
        print(f'{name}: {digest}')
    (ROOT / 'zephyr/patches.yml').write_text('\n'.join(manifest) + '\n')

if __name__ == '__main__':
    main()
